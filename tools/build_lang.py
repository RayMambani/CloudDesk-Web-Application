#!/usr/bin/env python3
"""Regenerates lang/*.php from the Android app's strings.xml files (same keys), plus
web-only extras. Run:  python3 tools/build_lang.py <path-to-android-res-folder>"""
import re, sys, os

RES = sys.argv[1] if len(sys.argv) > 1 else '../cloudDeskmobile-master/app/src/main/res'
OUT = os.path.join(os.path.dirname(__file__), '..', 'lang')
FOLDERS = {'en': 'values', 'nso': 'values-b+nso', 've': 'values-ve', 'ts': 'values-ts'}

# Web-only strings (English; other languages fall back to English until translated).
EXTRAS = {
    'nav_dashboard': 'Dashboard',
    'nav_notifications': 'Notifications',
    'notif_view_all': 'View all',
    'notif_none': 'No notifications yet.',
    'notif_mark_all_read': 'Mark all as read',
    'notif_enable_desktop': 'Enable desktop alerts',
    'notif_new_ticket_title': 'New ticket',
    'history_priority_format': 'Priority changed: %1$s → %2$s',
}
SKIP = {'default_web_client_id', 'app_name', 'notif_channel_name', 'notif_channel_description'}

def php_str(s):
    return "'" + s.replace('\\', '\\\\').replace("'", "\\'") + "'"

def unescape(v):
    v = v.replace('\\n', '\n').replace("\\'", "'").replace('\\"', '"').replace('\\@', '@').replace('\\?', '?')
    v = re.sub(r'\\u([0-9a-fA-F]{4})', lambda m: chr(int(m.group(1), 16)), v)
    return v

for code, folder in FOLDERS.items():
    xml = open(os.path.join(RES, folder, 'strings.xml'), encoding='utf8').read()
    items = {}
    for m in re.finditer(r'<string name="([^"]+)"[^>]*>(.*?)</string>', xml, re.S):
        if m.group(1) in SKIP:
            continue
        items[m.group(1)] = unescape(m.group(2))
    if code == 'en':
        items.update(EXTRAS)
    lines = ['<?php', '// Generated by tools/build_lang.py from the Android strings.xml (same key names).', 'return [']
    for k in sorted(items):
        lines.append(f"    {php_str(k)} => {php_str(items[k])},")
    lines.append('];')
    open(os.path.join(OUT, code + '.php'), 'w', encoding='utf8').write('\n'.join(lines) + '\n')
    print(code, len(items))
